#!/usr/bin/env bash
# Build the scroll-scrub frame sequence from the source video.
#
#   ./tools/build-frames.sh [FRAMES] [DESKTOP_W] [MOBILE_W] [QUALITY]
#
# The source clip is 71 real frames (2.99s @ 24fps), so anything above that is
# motion-interpolated. Interpolation is the slow part: cost scales with
# FRAMES x width, and minterpolate runs single-threaded per output frame.
set -euo pipefail

FRAMES=${1:-300}
DESKTOP_W=${2:-1920}
MOBILE_W=${3:-960}
QUALITY=${4:-5}

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="$ROOT/media/approach.mp4"
[ -f "$SRC" ] || { echo "missing $SRC" >&2; exit 1; }

DUR=$(ffprobe -v error -show_entries format=duration -of csv=p=0 "$SRC")
FPS=$(python3 -c "print(f'{$FRAMES/$DUR:.6f}')")

echo "source   : $SRC (${DUR}s)"
echo "frames   : $FRAMES  -> synthetic ${FPS}fps"

build_set () {
  local name="$1"
  local width="$2"
  local out="$ROOT/assets/frames/$name"
  rm -rf "$out"; mkdir -p "$out"
  echo "building : $name @ ${width}px"
  ffmpeg -v error -stats -i "$SRC" \
    -vf "scale=${width}:-2,minterpolate=fps=${FPS}:mi_mode=mci:mc_mode=aobmc:me_mode=bidir:me=epzs" \
    -frames:v "$FRAMES" -q:v "$QUALITY" "$out/f%04d.jpg"
  # ffmpeg can land one frame short of the request on the final boundary;
  # pad by duplicating the last frame so the manifest count is always exact.
  local have; have=$(find "$out" -name 'f*.jpg' | wc -l | tr -d ' ')
  while [ "$have" -lt "$FRAMES" ]; do
    have=$((have+1))
    cp "$(find "$out" -name 'f*.jpg' | sort | tail -1)" "$(printf '%s/f%04d.jpg' "$out" "$have")"
  done
  echo "  -> $have frames, $(du -sh "$out" | cut -f1)"
}

build_set desktop "$DESKTOP_W"
build_set mobile  "$MOBILE_W"

cat > "$ROOT/assets/js/frames.manifest.js" <<MANIFEST
/* Generated by tools/build-frames.sh — do not edit by hand. */
window.FRAME_MANIFEST = {
  count: $FRAMES,
  pad: 4,
  sets: [
    { name: "mobile",  width: $MOBILE_W,  maxViewport: 900 },
    { name: "desktop", width: $DESKTOP_W, maxViewport: Infinity }
  ],
  path: (set, i) => \`assets/frames/\${set}/f\${String(i + 1).padStart(4, "0")}.jpg\`
};
MANIFEST

echo "wrote    : assets/js/frames.manifest.js ($FRAMES frames)"
