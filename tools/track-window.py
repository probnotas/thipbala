#!/usr/bin/env python3
"""
Re-derive assets/js/window-track.js from the frame sequence.

    python3 tools/track-window.py [--frames N] [--last-tracked 280]

The cockpit window's dark opening is found per frame by connected-component
search on the thresholded image, discarding the whole-frame dark background
and any blob that drifts off the centre. Width is then fitted as an
exponential (constant-velocity approach to a plane) and the centre as a
line, both over the range where detection is reliable.

Needs numpy + pillow:  pip3 install numpy pillow
"""
import argparse, json, sys
from collections import deque

import numpy as np
from PIL import Image

AP = argparse.ArgumentParser()
AP.add_argument("--dir", default="assets/frames/desktop")
AP.add_argument("--frames", type=int, default=600)
AP.add_argument("--last-tracked", type=int, default=280,
                help="last frame the opening is still fully on screen")
AP.add_argument("--step", type=int, default=10)
AP.add_argument("--width", type=int, default=200, help="analysis resolution")
AP.add_argument("--thresh", type=int, default=30)
AP.add_argument("--out", default="assets/js/window-track.js")
A = AP.parse_args()


def load(i):
    im = Image.open(f"{A.dir}/f{i+1:04d}.jpg").convert("L")
    h = round(im.height * A.width / im.width)
    return np.asarray(im.resize((A.width, h), Image.BILINEAR)).astype(np.int16)


def opening(i):
    """largest dark blob that is not the whole-frame background"""
    g = load(i); H, W = g.shape
    dark = g < A.thresh
    seen = np.zeros_like(dark, bool)
    best = None
    for sy in range(0, H, 2):
        for sx in range(0, W, 2):
            if not dark[sy, sx] or seen[sy, sx]:
                continue
            q = deque([(sy, sx)]); seen[sy, sx] = True
            y0 = y1 = sy; x0 = x1 = sx; n = 0
            while q:
                y, x = q.popleft(); n += 1
                y0 = min(y0, y); y1 = max(y1, y)
                x0 = min(x0, x); x1 = max(x1, x)
                for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    ny, nx = y + dy, x + dx
                    if 0 <= ny < H and 0 <= nx < W and dark[ny, nx] and not seen[ny, nx]:
                        seen[ny, nx] = True; q.append((ny, nx))
            if (x1-x0)/W > 0.96 and (y1-y0)/H > 0.96:   # frame-wide background
                continue
            if n < 40:
                continue
            if best is None or n > best[0]:
                best = (n, x0, y0, x1, y1)
    if best is None:
        return None
    _, x0, y0, x1, y1 = best
    return dict(i=i, cx=((x0+x1)/2)/W, cy=((y0+y1)/2)/H, w=(x1-x0)/W)


rows = []
for i in range(0, A.last_tracked + 1, A.step):
    r = opening(i)
    if r:
        rows.append(r)
        print(f"  f{i:03d} c=({r['cx']:.3f},{r['cy']:.3f}) w={r['w']:.3f}", flush=True)

if len(rows) < 6:
    sys.exit("too few tracked frames — lower --thresh or check --dir")

# reject blobs that wandered off the centre line
mcx = float(np.median([r["cx"] for r in rows]))
keep = [r for r in rows if abs(r["cx"] - mcx) < 0.05 and r["w"] > 0.10]
print(f"kept {len(keep)}/{len(rows)} after outlier rejection")

i = np.array([r["i"] for r in keep], float)
w = np.array([r["w"] for r in keep], float)
b, a = np.polyfit(i, np.log(w), 1)
err = np.abs(np.exp(a + b*i) - w) / w
print(f"width fit: {np.exp(a):.4f} * {np.exp(b):.5f}^i   "
      f"({100*(np.exp(b)-1):.3f}%/frame)  mean err {err.mean()*100:.1f}%")
if err.mean() > 0.06:
    print("WARNING: poor fit — the motion may not be a clean push-in", file=sys.stderr)

scx, icx = np.polyfit(i, np.array([r["cx"] for r in keep]), 1)
scy, icy = np.polyfit(i, np.array([r["cy"] for r in keep]), 1)

open(A.out, "w").write(f"""/* =====================================================================
   WINDOW TRACK — where the cockpit window opening sits, per frame.
   GENERATED by tools/track-window.py — see tools/README-tracking.md.

   Measured, not guessed: the dark opening was detected across frames
   0-{A.last_tracked} of the clip, then fitted. Width grows exponentially at
   {100*(np.exp(b)-1):.3f}%/frame, which is what a constant-velocity approach to a
   plane looks like; the fit holds to {err.mean()*100:.1f}% mean error over that range.
   The centre drifts slightly and is linear over the same range, then held.

   Everything is a fraction of the RENDERED FRAME (not the viewport), so
   it survives the canvas `cover` crop at any aspect ratio.
   ===================================================================== */

window.WINDOW_TRACK = (function () {{
  const W0 = {np.exp(a):.4f}, RATE = {np.exp(b):.5f};      // width = W0 * RATE^i
  const CX0 = {icx:.4f}, CX_SLOPE = {scx:.3e}; // centre drift per frame
  const CY0 = {icy:.4f}, CY_SLOPE = {scy:.3e};
  const HOLD = {A.last_tracked};                       // last reliably tracked frame

  return {{
    width: i => W0 * Math.pow(RATE, i),
    cx:    i => CX0 + CX_SLOPE * Math.min(i, HOLD),
    cy:    i => CY0 + CY_SLOPE * Math.min(i, HOLD),

    // Greeting text width as a fraction of the opening. 0.55 keeps it
    // clear of the chevron struts that frame the opening's narrow waist.
    fill: 0.55,

    // Fade the greeting out as we pass through the opening, finishing
    // well before the star chart begins its own dissolve.
    fadeFrom: 0.75,
    fadeTo:   1.25
  }};
}})();
""")
print(f"wrote {A.out}")
